/**
 * Email Report
 *
 * Sends an HTML-formatted reconciliation report via the existing emailService.
 * Only sends when issues are found.
 */

import { emailService } from '../../../lib/email';
import { config } from '../../../config';
import type {
  ReconciliationReport,
  MarketplaceReconciliationResult,
} from '../reconciliation.types';

export async function sendEmailReport(report: ReconciliationReport): Promise<void> {
  if (!report.summary.hasIssues) {
    return; // Don't send email when everything is healthy
  }

  const s = report.summary;
  const subject = `[Reconciliation] ${s.totalMissing} missing | ${s.totalStuck} stuck | ${s.totalUnconverted} unconverted`;

  const html = buildHtmlReport(report);

  await emailService.sendEmail({
    to: config.DEVELOPMENT_TEAM_EMAIL || 'ukss-team@velsof.com',
    subject,
    html,
    text: buildTextReport(report),
  });
}

function buildHtmlReport(report: ReconciliationReport): string {
  const s = report.summary;

  let html = `
<!DOCTYPE html>
<html>
<head>
  <meta charset="utf-8">
  <style>
    body { font-family: 'Segoe UI', Arial, sans-serif; color: #333; max-width: 700px; margin: 0 auto; }
    .header { background: #1a1a2e; color: #fff; padding: 20px; border-radius: 8px 8px 0 0; }
    .header h1 { margin: 0; font-size: 20px; }
    .header .meta { color: #aaa; font-size: 13px; margin-top: 4px; }
    .summary { background: ${s.hasIssues ? '#fff3cd' : '#d4edda'}; padding: 12px 20px; font-weight: 600; }
    .content { padding: 16px 20px; }
    .marketplace { margin-bottom: 20px; }
    .marketplace h3 { margin: 0 0 8px 0; border-bottom: 1px solid #ddd; padding-bottom: 4px; }
    .ok { color: #28a745; }
    .warn { color: #ffc107; }
    .error { color: #dc3545; }
    table { border-collapse: collapse; width: 100%; font-size: 13px; margin: 6px 0; }
    th, td { text-align: left; padding: 4px 8px; border-bottom: 1px solid #eee; }
    th { background: #f8f9fa; }
    .footer { background: #f8f9fa; padding: 12px 20px; font-size: 12px; color: #666; border-radius: 0 0 8px 8px; }
  </style>
</head>
<body>
  <div class="header">
    <h1>Order Reconciliation Report</h1>
    <div class="meta">Run: ${report.runDate.toISOString()} | Window: Last ${report.windowHours} hours</div>
  </div>
  <div class="summary">
    ${s.totalMissing} missing | ${s.totalProductMismatches} product mismatches | ${s.totalStuck} stuck | ${s.totalUnconverted} unconverted
  </div>
  <div class="content">`;

  for (const result of report.results) {
    html += renderMarketplaceHtml(result);
  }

  html += `
  </div>
  <div class="footer">
    Generated by Stock2 Order Reconciliation Tool
  </div>
</body>
</html>`;

  return html;
}

function renderMarketplaceHtml(result: MarketplaceReconciliationResult): string {
  let html = `<div class="marketplace"><h3>${result.marketplace}</h3>`;

  if (result.apiError) {
    html += `<p class="error">API Error: ${escapeHtml(result.apiError)}</p>`;
  }

  if (result.missingOrders) {
    const mo = result.missingOrders;
    html += `<p>API: ${mo.apiOrderCount} | DB: ${mo.dbOrderCount}`;
    if (mo.missingOrders.length > 0) {
      html += ` | <span class="error">Missing: ${mo.missingOrders.length}</span></p>`;
      html += `<table><tr><th>Order ID</th><th>Store</th><th>Date</th></tr>`;
      for (const o of mo.missingOrders.slice(0, 20)) {
        html += `<tr><td>${escapeHtml(o.orderId)}</td><td>${escapeHtml(o.storeName)}</td><td>${o.orderDate.toISOString()}</td></tr>`;
      }
      if (mo.missingOrders.length > 20) {
        html += `<tr><td colspan="3">... and ${mo.missingOrders.length - 20} more</td></tr>`;
      }
      html += `</table>`;
    } else {
      html += ` | <span class="ok">All present</span></p>`;
    }
  }

  if (result.missingProducts && result.missingProducts.mismatches.length > 0) {
    const mp = result.missingProducts;
    html += `<p class="warn">Product mismatches: ${mp.mismatches.length}</p>`;
    html += `<table><tr><th>Order ID</th><th>Store</th><th>API Qty</th><th>DB Qty</th></tr>`;
    for (const m of mp.mismatches.slice(0, 20)) {
      html += `<tr><td>${escapeHtml(m.orderId)}</td><td>${escapeHtml(m.storeName)}</td><td>${m.apiQuantity}</td><td>${m.dbQuantity}</td></tr>`;
    }
    html += `</table>`;
  }

  if (result.statusSync.stuckStatuses.length > 0) {
    html += `<p class="warn">Stuck statuses: ${result.statusSync.stuckStatuses.length}</p>`;
    html += `<table><tr><th>Order ID</th><th>Store</th><th>Status</th><th>Waiting (h)</th></tr>`;
    for (const s of result.statusSync.stuckStatuses.slice(0, 20)) {
      html += `<tr><td>${escapeHtml(s.orderId)}</td><td>${escapeHtml(s.storeName)}</td><td>${escapeHtml(s.statusToUpdate)}</td><td>${s.waitingSinceHours}</td></tr>`;
    }
    html += `</table>`;
  }

  if (result.unconvertedOrders.unconvertedOrders.length > 0) {
    html += `<p class="warn">Unconverted orders: ${result.unconvertedOrders.unconvertedOrders.length}</p>`;
    html += `<table><tr><th>Order ID</th><th>Store</th><th>Age (h)</th></tr>`;
    for (const o of result.unconvertedOrders.unconvertedOrders.slice(0, 20)) {
      html += `<tr><td>${escapeHtml(o.orderId)}</td><td>${escapeHtml(o.storeName)}</td><td>${o.ageHours}</td></tr>`;
    }
    html += `</table>`;
  }

  html += `</div>`;
  return html;
}

function buildTextReport(report: ReconciliationReport): string {
  const s = report.summary;
  let text = `ORDER RECONCILIATION REPORT\n`;
  text += `Run: ${report.runDate.toISOString()} | Window: Last ${report.windowHours} hours\n\n`;
  text += `SUMMARY: ${s.totalMissing} missing | ${s.totalProductMismatches} product mismatches | ${s.totalStuck} stuck | ${s.totalUnconverted} unconverted\n\n`;

  for (const r of report.results) {
    text += `${r.marketplace}\n`;
    if (r.apiError) text += `  API Error: ${r.apiError}\n`;
    if (r.missingOrders) text += `  Missing Orders: ${r.missingOrders.missingOrders.length}\n`;
    if (r.missingProducts) text += `  Product Mismatches: ${r.missingProducts.mismatches.length}\n`;
    text += `  Stuck Statuses: ${r.statusSync.stuckStatuses.length}\n`;
    text += `  Unconverted: ${r.unconvertedOrders.unconvertedOrders.length}\n\n`;
  }

  return text;
}

function escapeHtml(str: string): string {
  return str
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}
