async function main() {
  console.log(`[seed] Inserting ${events.length} events into jsa_sales_events...`);

  let inserted = 0;
  for (const e of events) {
    const result = await prisma.$executeRawUnsafe(
      `INSERT IGNORE INTO jsa_sales_events
        (event_name, event_category, event_type, region,
         buying_window_start, buying_window_end, event_start_date, event_end_date,
         year, is_active, notes)
       VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, TRUE, ?)`,
      e.event_name,
      e.event_category,
      e.event_type,
      e.region,
      e.buying_window_start,
      e.buying_window_end,
      e.event_start_date,
      e.event_end_date,
      e.year,
      e.notes,
    );
    inserted += result;
  }

  console.log(`[seed] Done. ${inserted} new events inserted (${events.length} total attempted).`);
}

main()
  .catch((err) => {
    console.error('[seed] Failed to seed events:', err);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
    process.exit(0);
  });
